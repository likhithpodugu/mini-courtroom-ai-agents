"""
Mini Courtroom — litigation-prep simulator: stress-test arguments,
find weaknesses, get a cited case brief. Not legal advice.

    python app.py --sample rent-deposit        # CLI, sample case
    python app.py --case "Priya paid ..."      # CLI, your own case
    python app.py --serve                      # Web UI on :5000

LLM: by default speeches are generated by a real LLM — Groq when
GROQ_API_KEY is set, else OpenAI when OPENAI_API_KEY is set,
otherwise the free no-key Pollinations API.
Use --no-llm for the offline local engine. The debate runs until the
Judge says it has heard enough to prepare a preliminary assessment
(min 2, max 6 rounds — see --max-rounds).

Web API:  POST /api/hearing {"case": "..."} -> evidence matrix +
          verified legal sources + transcript + Judge's critique +
          case brief (Markdown)
          GET  /api/samples                    -> the 3 sample cases
          GET  /api/legal-sources              -> verified source set
          GET  /health
"""
import argparse
import json
import os
import sys

from courtroom import run_hearing
from legal_sources import SOURCES
from llm import get_client
from samples import SAMPLES


def print_hearing(result: dict) -> None:
    s = result["case_summary"]
    print(f"\nCASE: {s['issue']} — {s['plaintiff']} vs {s['defendant']}")
    if s["amounts"]:
        print(f"Amount: {', '.join(s['amounts'])}")
    print(f"LLM: {result['llm_provider']} | Debate rounds: "
          f"{result['rounds_held']} (stopped by {result['stopped_by']})")
    print("=" * 70)
    print("\nEVIDENCE MATRIX")
    for r in result["evidence_matrix"]:
        print(f"  [{r['status']}] {r['fact']} — {r['evidence']} "
              f"(supports {r['supports']})")
    print("\nVERIFIED LEGAL SOURCES")
    for src in result["legal_sources"]:
        print(f"  - {src['citation']} — {src['url']}")
    if not result["legal_sources"]:
        print("  - None retrieved — legal claims are unsupported.")
    print("=" * 70)
    for t in result["transcript"]:
        print(f"\n[Round {t['round_no']} — {t['round_name']}] {t['speaker']} "
              f"({t['role']}) [{t['source']}]")
        print("-" * 70)
        print(t["text"])
    for c in result["judge_checks"]:
        print(f"\n[Judge check after round {c['after_round']}] "
              f"{'ENOUGH' if c['sufficient'] else 'CONTINUE'} — {c['reason']}")
    a = result["assessment"]
    print("\n" + "=" * 70)
    print(f"PRELIMINARY ASSESSMENT: {a['assessment']}")
    print(f"Rubric (argument quality, not a probability) — Claimant "
          f"{a['prosecution_avg']}/10 | Respondent {a['defense_avg']}/10")
    print("Supporting factors:")
    for f in a["supporting_factors"]:
        print(f"  + {f}")
    print("Weaknesses:")
    for f in a["weaknesses"]:
        print(f"  - {f}")
    print("Missing evidence:")
    for f in a["missing_evidence"]:
        print(f"  ? {f}")
    print(f"\n{result['disclaimer']}")
    print("\nCase brief (Markdown) is in the API response as "
          "'brief_markdown'.")


def serve(llm=None):
    try:
        from flask import Flask, jsonify, render_template, request
    except ImportError:
        sys.exit("Flask is not installed — run: pip install -r requirements.txt")
    app = Flask(__name__)
    llm = llm if llm is not None else get_client()
    print(f"LLM provider: {llm.provider} ({llm.model})")

    @app.get("/")
    def index():
        return render_template("index.html", samples=SAMPLES,
                               llm_provider=llm.provider)

    @app.get("/health")
    def health():
        return {"ok": True, "llm_provider": llm.provider}

    @app.get("/api/samples")
    def samples():
        return jsonify(SAMPLES)

    @app.get("/api/legal-sources")
    def legal_sources():
        return jsonify(SOURCES)

    @app.post("/api/hearing")
    def hearing():
        data = request.get_json(force=True, silent=True) or {}
        case = (data.get("case") or "").strip()
        if len(case) < 20:
            return jsonify({"error": "Please describe the case in at least "
                                     "a sentence or two (20+ characters)."}), 400
        try:
            return jsonify(run_hearing(case, llm=llm))
        except ValueError as e:
            return jsonify({"error": str(e)}), 400

    port = int(os.environ.get("PORT", "5000"))
    print(f"Mini Courtroom running at http://127.0.0.1:{port}")
    app.run(host="0.0.0.0", port=port)


def main():
    p = argparse.ArgumentParser(
        description="Mini Courtroom — litigation-prep simulator: "
                    "evidence matrix, verified sources, debate, "
                    "Judge's critique, case brief. Not legal advice.")
    p.add_argument("--case", help="Problem statement / case facts")
    p.add_argument("--sample", choices=[s["id"] for s in SAMPLES],
                   help="Run a built-in sample case")
    p.add_argument("--serve", action="store_true", help="Start the web UI")
    p.add_argument("--json", action="store_true", help="Print raw JSON (CLI)")
    p.add_argument("--no-llm", action="store_true",
                   help="Use the offline local engine instead of the LLM")
    p.add_argument("--max-rounds", type=int, default=6,
                   help="Maximum debate rounds before the Judge must assess")
    args = p.parse_args()

    llm = None if args.no_llm else get_client()
    if args.serve:
        serve(llm)
        return
    if args.sample:
        case = next(s["case"] for s in SAMPLES if s["id"] == args.sample)
    elif args.case:
        case = args.case
    else:
        p.print_help()
        sys.exit(1)
    if not args.json:
        print(f"LLM provider: {llm.provider if llm else 'local (no LLM)'}")
    result = run_hearing(case, llm=llm, max_rounds=args.max_rounds)
    if args.json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
    else:
        print_hearing(result)


if __name__ == "__main__":
    main()
